// Command genlifetables regenerates data/lifetables/who2019.yaml from the
// public WHO APIs:
//
//   - Global Health Observatory life tables: nqx (LIFE_0000000030) and
//     ex (LIFE_0000000035) by five-year age group, sex and country.
//   - Global Health Estimates (GHE_FULL): deaths by cause, age group, sex and
//     country, used for the share of deaths per cause group.
//
// Five-year probabilities are turned into single-year ones by interpolating
// the log of the force of mortality between band midpoints; remaining life
// expectancy is recomputed from the single-year table plus WHO's e(85).
//
// Usage: go run ./tools/genlifetables -out data/lifetables/who2019.yaml
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"math"
	"net/http"
	"net/url"
	"os"
	"strings"
	"time"
)

const (
	ghoBase = "https://ghoapi.azureedge.net/api/"
	gheBase = "https://xmart-api-public.who.int/DEX_CMS/GHE_FULL"

	firstAge = 18
	lastAge  = 84
)

type region struct {
	code   string // our id
	gho    string // GHO SpatialDim
	ghe    string // GHE country code, "" = sum over all countries
	ru, en string
}

var regions = []region{
	{code: "world", gho: "GLOBAL", ghe: "", ru: "Мир (в среднем по ВОЗ)", en: "World (WHO average)"},
	{code: "rus", gho: "RUS", ghe: "RUS", ru: "Россия", en: "Russia"},
	{code: "usa", gho: "USA", ghe: "USA", ru: "США", en: "USA"},
}

var sexes = []struct{ code, gho, ghe string }{
	{"male", "SEX_MLE", "MALE"},
	{"female", "SEX_FMLE", "FEMALE"},
}

// GHE cause codes used to build the game's cause groups.
const (
	gheAll       = 0
	gheCancer    = 610
	gheDiabetes  = 800
	gheAlcohol   = 860
	gheDrugs     = 870
	gheCVD       = 1100
	gheDigestive = 1210
	gheInjuries  = 1510
	ghePoisoning = 1540
	gheSelfHarm  = 1610
)

var gheCauses = []int{gheAll, gheCancer, gheDiabetes, gheAlcohol, gheDrugs, gheCVD, gheDigestive, gheInjuries, ghePoisoning, gheSelfHarm}

// bands are the WHO five-year groups overlapping the playable ages.
var bands = [][2]int{{15, 19}, {20, 24}, {25, 29}, {30, 34}, {35, 39}, {40, 44}, {45, 49}, {50, 54}, {55, 59}, {60, 64}, {65, 69}, {70, 74}, {75, 79}, {80, 84}}

func main() {
	out := flag.String("out", "data/lifetables/who2019.yaml", "output file")
	year := flag.Int("year", 2019, "reference year")
	flag.Parse()

	nqx := fetchGHO("LIFE_0000000030", *year)
	ex := fetchGHO("LIFE_0000000035", *year)
	deaths := fetchGHE(*year)

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by tools/genlifetables — do not edit by hand.\n")
	fmt.Fprintf(&b, "# Single-year death probabilities (q), remaining life expectancy (ex) and\n")
	fmt.Fprintf(&b, "# cause-of-death shares per five-year band, by region and sex, for %d.\n", *year)
	fmt.Fprintf(&b, "year: %d\nfirst_age: %d\nlast_age: %d\n", *year, firstAge, lastAge)
	b.WriteString("sources:\n")
	b.WriteString("  - name: \"WHO Global Health Observatory — Life tables by country: nqx and ex (LIFE_0000000030, LIFE_0000000035)\"\n")
	b.WriteString("    url: \"https://www.who.int/data/gho/data/indicators/indicator-details/GHO/gho-ghe-life-tables-by-country\"\n")
	b.WriteString("  - name: \"WHO Global Health Estimates 2021 — Deaths by cause, age, sex, by country and by region, 2000–2021\"\n")
	b.WriteString("    url: \"https://www.who.int/data/global-health-estimates\"\n")
	b.WriteString("tables:\n")

	for _, r := range regions {
		for _, s := range sexes {
			key := r.gho + "|" + s.gho
			q5 := map[int]float64{}
			for _, bd := range bands {
				v, ok := nqx[key+"|"+ageGroupGHO(bd)]
				if !ok {
					log.Fatalf("missing nqx for %s %v", key, bd)
				}
				q5[bd[0]] = v
			}
			e85, ok := ex[key+"|AGEGROUP_YEARS85PLUS"]
			if !ok {
				log.Fatalf("missing e85 for %s", key)
			}
			q := singleYear(q5)
			e := lifeExpectancy(q, e85)
			check := ex[key+"|AGEGROUP_YEARS20-24"]
			log.Printf("%s/%s: q18=%.5f q50=%.5f q84=%.4f e20=%.2f (WHO %.2f) S(18→85)=%.3f",
				r.code, s.code, q[0], q[50-firstAge], q[lastAge-firstAge], e[20-firstAge], check, survival(q))

			fmt.Fprintf(&b, "  - id: %s_%s\n    region: %s\n    sex: %s\n", r.code, s.code, r.code, s.code)
			fmt.Fprintf(&b, "    name: {ru: %q, en: %q}\n", r.ru, r.en)
			b.WriteString("    q: [" + joinFloats(q, 6) + "]\n")
			b.WriteString("    ex: [" + joinFloats(e, 2) + "]\n")
			b.WriteString("    bands:\n")
			for _, bd := range bands {
				f := fractions(deaths, r.ghe, s.ghe, bd)
				fmt.Fprintf(&b, "      - {from: %d, to: %d, fractions: {cardiovascular: %.4f, oncology: %.4f, liver: %.4f, trauma: %.4f, self_harm: %.4f, other: %.4f}}\n",
					bd[0], bd[1], f[0], f[1], f[2], f[3], f[4], f[5])
			}
		}
	}

	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s", *out)
}

func ageGroupGHO(bd [2]int) string { return fmt.Sprintf("AGEGROUP_YEARS%02d-%02d", bd[0], bd[1]) }
func ageGroupGHE(bd [2]int) string { return fmt.Sprintf("Y%dT%d", bd[0], bd[1]) }

// singleYear interpolates log(mu) linearly between band midpoints, where mu is
// the constant force of mortality that reproduces each band's nqx.
func singleYear(q5 map[int]float64) []float64 {
	type pt struct{ x, lmu float64 }
	var pts []pt
	for _, bd := range bands {
		mu := -math.Log(1-q5[bd[0]]) / 5
		pts = append(pts, pt{float64(bd[0]) + 2.5, math.Log(mu)})
	}
	out := make([]float64, 0, lastAge-firstAge+1)
	for a := firstAge; a <= lastAge; a++ {
		x := float64(a) + 0.5
		i := 0
		for i < len(pts)-2 && x > pts[i+1].x {
			i++
		}
		p0, p1 := pts[i], pts[i+1]
		t := (x - p0.x) / (p1.x - p0.x)
		lmu := p0.lmu + t*(p1.lmu-p0.lmu)
		out = append(out, 1-math.Exp(-math.Exp(lmu)))
	}
	return out
}

func lifeExpectancy(q []float64, e85 float64) []float64 {
	n := len(q)
	l := make([]float64, n+1)
	l[0] = 1
	for i := range q {
		l[i+1] = l[i] * (1 - q[i])
	}
	e := make([]float64, n)
	tail := l[n] * e85
	for i := n - 1; i >= 0; i-- {
		tail += (l[i] + l[i+1]) / 2
		e[i] = tail / l[i]
	}
	return e
}

func survival(q []float64) float64 {
	s := 1.0
	for _, v := range q {
		s *= 1 - v
	}
	return s
}

// fractions returns shares for cardiovascular, oncology, liver, trauma,
// self_harm and other, in that order.
func fractions(d map[string]float64, country, sex string, bd [2]int) [6]float64 {
	get := func(cause int) float64 {
		return d[fmt.Sprintf("%s|%s|%s|%d", country, sex, ageGroupGHE(bd), cause)]
	}
	all := get(gheAll)
	if all <= 0 {
		log.Fatalf("no deaths for %q %s %v", country, sex, bd)
	}
	cvd := get(gheCVD) + get(gheDiabetes)
	onc := get(gheCancer)
	liv := get(gheDigestive) + get(gheAlcohol) + get(gheDrugs) + get(ghePoisoning)
	tra := get(gheInjuries) - get(ghePoisoning) - get(gheSelfHarm)
	slf := get(gheSelfHarm)
	oth := all - cvd - onc - liv - tra - slf
	f := [6]float64{cvd / all, onc / all, liv / all, tra / all, slf / all, oth / all}
	// Round so the six shares still add up to exactly 1 at 4 decimals.
	sum := 0.0
	for i := 0; i < 5; i++ {
		f[i] = math.Round(f[i]*1e4) / 1e4
		sum += f[i]
	}
	f[5] = math.Round((1-sum)*1e4) / 1e4
	return f
}

func joinFloats(v []float64, prec int) string {
	parts := make([]string, len(v))
	for i, x := range v {
		parts[i] = fmt.Sprintf("%.*f", prec, x)
	}
	return strings.Join(parts, ", ")
}

// fetchGHO returns indicator values keyed by "SpatialDim|Sex|AgeGroup".
func fetchGHO(indicator string, year int) map[string]float64 {
	var spatial []string
	for _, r := range regions {
		spatial = append(spatial, "'"+r.gho+"'")
	}
	filter := fmt.Sprintf("SpatialDim in (%s) and TimeDim eq %d", strings.Join(spatial, ","), year)
	var resp struct {
		Value []struct {
			SpatialDim   string
			Dim1         string
			Dim2         string
			NumericValue float64
		} `json:"value"`
	}
	getJSON(ghoBase+indicator+"?$filter="+url.PathEscape(filter), &resp)
	out := map[string]float64{}
	for _, v := range resp.Value {
		out[v.SpatialDim+"|"+v.Dim1+"|"+v.Dim2] = v.NumericValue
	}
	if len(out) == 0 {
		log.Fatalf("%s: no data for %d", indicator, year)
	}
	return out
}

// fetchGHE returns death counts keyed by "country|sex|agegroup|cause"; the
// empty country holds the sum over every country (the world).
func fetchGHE(year int) map[string]float64 {
	out := map[string]float64{}
	for _, cause := range gheCauses {
		filter := fmt.Sprintf("DIM_YEAR_CODE eq %d and DIM_GHECAUSE_CODE eq %d and (DIM_SEX_CODE eq 'MALE' or DIM_SEX_CODE eq 'FEMALE')", year, cause)
		for skip := 0; ; skip += 5000 {
			var resp struct {
				Value []struct {
					Country string  `json:"DIM_COUNTRY_CODE"`
					Sex     string  `json:"DIM_SEX_CODE"`
					Age     string  `json:"DIM_AGEGROUP_CODE"`
					Deaths  float64 `json:"VAL_DTHS_COUNT_NUMERIC"`
				} `json:"value"`
			}
			q := url.Values{}
			q.Set("$filter", filter)
			q.Set("$select", "DIM_COUNTRY_CODE,DIM_SEX_CODE,DIM_AGEGROUP_CODE,VAL_DTHS_COUNT_NUMERIC")
			q.Set("$top", "5000")
			q.Set("$skip", fmt.Sprint(skip))
			getJSON(gheBase+"?"+strings.ReplaceAll(q.Encode(), "+", "%20"), &resp)
			for _, v := range resp.Value {
				k := fmt.Sprintf("|%s|%s|%d", v.Sex, v.Age, cause)
				out[v.Country+k] += v.Deaths
				out[k] += v.Deaths
			}
			if len(resp.Value) < 5000 {
				break
			}
		}
		log.Printf("GHE cause %d fetched", cause)
	}
	return out
}

func getJSON(u string, v any) {
	client := &http.Client{Timeout: 120 * time.Second}
	var last error
	for attempt := 1; attempt <= 5; attempt++ {
		resp, err := client.Get(u)
		if err == nil {
			body, rerr := io.ReadAll(resp.Body)
			_ = resp.Body.Close()
			if rerr == nil && resp.StatusCode == http.StatusOK {
				if err := json.Unmarshal(body, v); err != nil {
					log.Fatalf("decode %s: %v", u, err)
				}
				return
			}
			err = fmt.Errorf("status %d: %.200s", resp.StatusCode, body)
		}
		last = err
		time.Sleep(time.Duration(attempt) * 2 * time.Second)
	}
	log.Fatalf("GET %s: %v", u, last)
}
